def check(condition: object, detail: str) -> None:
    global CHECKS
    if not condition:
        raise AssertionError(f"{detail}\nFAILED CHECK: {detail.split(': ', 1)[0]}")
    CHECKS += 1


class Blocked(BaseException):
    """Still waiting when the alarm rang. Not an OSError (TimeoutError is), which the code under test would catch."""


def outcome(call, *, seconds: int = 5) -> str:
    """What `call` did: "ok", "refused: ...", "raised: ...", or "blocked" when it was still waiting after `seconds`."""
    def blocked(_signum, _frame):
        raise Blocked

    previous = signal.signal(signal.SIGALRM, blocked)
    signal.alarm(seconds)
    try:
        call()
    except Blocked:
        return "blocked"
    except SystemExit as stop:
        return f"refused: {stop}"
    except Exception as exc:  # noqa: BLE001 -- what the code raised is the observation
        return f"raised: {type(exc).__name__}: {exc}"
    finally:
        signal.alarm(0)
        signal.signal(signal.SIGALRM, previous)
    return "ok"


