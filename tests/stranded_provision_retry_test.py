CHECKS = 0
SEAM = "SWITCHYARD_PRIVILEGED_PROVISION_ROOT"
SLUG = "porter"
TENANT = "porter-agent"
TENANT_UID = 62260


def check(condition: bool, detail: str) -> None:
    global CHECKS
    assert condition, detail
    CHECKS += 1


def earlier_release_unit(unit: str) -> str:
    """The same plan's board unit as the release before SYRD-552 rendered it."""
    edits = (
        ("After=network.target postgresql.service\n", "After=network.target postgresql.service\nWants=postgresql.service\n"),
        ("StartLimitIntervalSec=5min\nStartLimitBurst=5\n", ""),
        ("Restart=on-failure\nRestartSec=30s\n", "Restart=always\nRestartSec=2\n"),
    )
    for old, new in edits:
        assert unit.count(old) == 1, f"the current render has changed shape: {old!r}"
        unit = unit.replace(old, new)
    return unit


class _StrandedHost:
    """Answers the precheck's probes as the host the VM was left as: unit listed, no database.

    With `fresh`, the host before the first run: nothing listed, so that run renders.
    """

    def __init__(self, *, fresh: bool = False) -> None:
        self.calls: list[list[str]] = []
        self.fresh = fresh

    def __call__(self, args, **kwargs):
        args = [str(a) for a in args]
        self.calls.append(args)
        if args[:3] == ["systemctl", "list-unit-files", "--no-legend"]:
            listed = "" if self.fresh else f"{SLUG}-ticket-board.service disabled\n"
            return subprocess.CompletedProcess(args, 0, stdout=listed, stderr="")
        if args[:2] == ["psql", "-XAt"]:
            return subprocess.CompletedProcess(args, 0, stdout="", stderr="")
        if len(args) >= 5 and args[:2] == ["git", "-C"] and args[3] == "status":
            return subprocess.CompletedProcess(args, 0, stdout="", stderr="")
        return subprocess.CompletedProcess(args, 0, stdout="", stderr="")


def _retry(tmp: Path, *, unit_edit, record: str, polkit_rules: Path | None = None, execute: bool = True) -> tuple[int | None, str, _StrandedHost, Path]:
    """Render once, leave its unit (as `unit_edit` makes it) and no database, and run `new` again."""
    from scripts.new_project_command import new_project_command

    owner = launcher.current_user_name()
    source = tmp / "repo"
    source.mkdir()
    repository = tmp / "project-repo"
    repository.mkdir()
    rendered = tmp / "rendered"
    new_project_command(SLUG, owner_user=owner, source_repo=source, repository=repository, output_dir=rendered,
                        runner=_StrandedHost(fresh=True), port_in_use=lambda _port: False, socket_exists=lambda _path: False)
    units = tmp / "systemd"
    units.mkdir()
    unit = (rendered / f"{SLUG}-ticket-board.service").read_text(encoding="utf-8")
    (units / f"{SLUG}-ticket-board.service").write_text(unit_edit(unit), encoding="utf-8")
    provision = tmp / "etc-switchyard"
    (provision / SLUG).mkdir(parents=True)
    plan_record = provision / SLUG / "plan.json"
    if record == "file":
        plan_record.write_bytes((rendered / "plan.json").read_bytes())
    elif record == "symlink":
        (tmp / "elsewhere.json").write_bytes((rendered / "plan.json").read_bytes())
        plan_record.symlink_to(tmp / "elsewhere.json")
    host = _StrandedHost()
    out = tmp / "out"
    saved_units, saved_rules = launcher.SYSTEMD_UNIT_DIR, launcher.POLKIT_RULES_DIR
    try:
        launcher.SYSTEMD_UNIT_DIR = units
        if polkit_rules is not None:
            launcher.POLKIT_RULES_DIR = polkit_rules
        with patch.dict(os.environ, {SEAM: str(provision)}):
            result = new_project_command(SLUG, owner_user=owner, source_repo=source, repository=repository,
                                         output_dir=out, execute=execute, runner=host,
                                         port_in_use=lambda _port: False, socket_exists=lambda _path: False)
        return result, "", host, out
    except SystemExit as exc:
        return None, str(exc), host, out
    finally:
        launcher.SYSTEMD_UNIT_DIR, launcher.POLKIT_RULES_DIR = saved_units, saved_rules


def _nothing_done(host: _StrandedHost, out: Path) -> bool:
    return not out.exists() and not any(c[:1] in (["sudo"], ["bash"], ["useradd"], ["install"]) for c in host.calls)


def test_the_packet_strands_exactly_a_unit_without_a_database() -> None:
    """The boundary this ticket is about, read from the packet the product renders."""
    with tempfile.TemporaryDirectory(prefix="syrd260-packet.") as raw:
        from scripts.new_project_command import new_project_command

        tmp = Path(raw)
        (tmp / "repo").mkdir()
        (tmp / "project-repo").mkdir()
        new_project_command(SLUG, owner_user=launcher.current_user_name(), source_repo=tmp / "repo",
                            repository=tmp / "project-repo", output_dir=tmp / "rendered", runner=_StrandedHost(fresh=True),
                            port_in_use=lambda _port: False, socket_exists=lambda _path: False)
        packet = (tmp / "rendered" / "operator-commands.sh").read_text(encoding="utf-8").splitlines()
    at = lambda needle: next(i for i, line in enumerate(packet) if needle in line)
    unit = at(f"\"$system_unit_candidate\" '/etc/systemd/system/{SLUG}-ticket-board.service'")
    rule = at(f"/etc/polkit-1/rules.d/49-{SLUG}-ticket-board-deploy.rules")
    database = at(f"{SLUG}-database.sql")
    check(unit < rule < database, f"the board unit, then the polkit rule that failed on the VM, then the database: {unit} {rule} {database}")


def test_a_run_from_an_earlier_release_is_sent_to_resume_provision() -> None:
    with tempfile.TemporaryDirectory(prefix="syrd260-earlier.") as raw:
        tmp = Path(raw)
        result, said, host, out = _retry(tmp, unit_edit=earlier_release_unit, record="file")
        record = tmp / "etc-switchyard" / SLUG / "plan.json"
    check(result is None and f"{SLUG}-ticket-board.service is installed but database '{SLUG}_ticket_board' does not exist" in said,
          f"the stranded state is still named: {said}")
    check(f"sudo switchyard resume-provision {SLUG}" in said and str(record) in said,
          f"and the way forward is root's record and the command that finishes from it: {said}")
    check("teardown" not in said, f"not a teardown of what the first run created: {said}")
    check(_nothing_done(host, out), f"and nothing was rendered, installed or run: {host.calls}")


def test_a_prerequisite_is_named_before_the_way_forward() -> None:
    with tempfile.TemporaryDirectory(prefix="syrd260-polkit.") as raw:
        tmp = Path(raw)
        result, said, host, out = _retry(tmp, unit_edit=earlier_release_unit, record="file",
                                         polkit_rules=tmp / "no-polkit" / "rules.d")
    items = said.split("\n- ")[1:]
    check(result is None and len(items) >= 2 and "polkit" in items[0] and "resume-provision" in items[-1],
          f"the missing polkit comes first, the stranded run and its way forward after it: {items}")
    check("Once anything listed above is fixed" in items[-1], f"and the way forward says so: {items[-1]}")
    check(_nothing_done(host, out), f"nothing was done: {host.calls}")


def test_without_roots_record_the_refusal_is_unchanged() -> None:
    for record in ("none", "symlink"):
        with tempfile.TemporaryDirectory(prefix=f"syrd260-{record}.") as raw:
            tmp = Path(raw)
            result, said, host, out = _retry(tmp, unit_edit=earlier_release_unit, record=record)
        check(result is None and f"switchyard teardown {SLUG} --dry-run" in said and "resume-provision" not in said,
              f"{record}: a unit with no root record is not called this project's run: {said}")
        check(_nothing_done(host, out), f"{record}: nothing was done: {host.calls}")


def test_a_run_from_this_release_still_finishes_by_running_new_again() -> None:
    with tempfile.TemporaryDirectory(prefix="syrd260-same.") as raw:
        tmp = Path(raw)
        result, said, _host, _out = _retry(tmp, unit_edit=lambda unit: unit, record="file", execute=False)
    check(result == 0, f"the same release's unit is this plan's, record or not (SYRD-261): {said}")


# --- the privileged half: resuming the stranded run from root's record -------------------------------------------------


def namespaces_available() -> bool:
    probe = subprocess.run(["unshare", "--user", "--map-root-user", "true"], capture_output=True, text=True)
    return probe.returncode == 0


def owner_patches(home: Path):
    from contextlib import ExitStack

    stack = ExitStack()
    stack.enter_context(patch.object(launcher, "uid_for_user", lambda name: TENANT_UID if name == TENANT else None))
    stack.enter_context(patch.object(launcher, "home_dir_for_user", lambda name: home if name == TENANT else None))
    real = launcher.pwd.getpwuid
    stack.enter_context(patch.object(
        launcher.pwd, "getpwuid",
        side_effect=lambda uid: SimpleNamespace(pw_gid=TENANT_UID, pw_name=TENANT) if uid == TENANT_UID else real(uid),
    ))
    return stack


def privileged_cases() -> None:
    from scripts.ticket_board.project_provision import build_plan

    with tempfile.TemporaryDirectory(prefix="syrd260-privileged.") as raw:
        root = Path(raw)
        root.chmod(0o755)
        os.environ[SEAM] = str(root)
        registry = root / "registry"
        registry.mkdir()
        release = root / "release"
        shutil.copytree(ROOT / "scripts", release / "scripts", ignore=shutil.ignore_patterns("__pycache__"))
        home = root / "home" / TENANT
        (home / "Projects" / SLUG).mkdir(parents=True)
        readme = home / "Projects" / SLUG / "README.md"
        readme.write_text("# porter\n", encoding="utf-8")
        (home / ".config" / SLUG).mkdir(parents=True)
        board_env = home / ".config" / SLUG / "ticket-board.env"
        board_env.write_text("TICKET_BOARD_TENANT_REPORT_TOKEN=seeded\n", encoding="utf-8")
        board_env.chmod(0o600)

        # What the interrupted run left: root's record and artifacts as the
        # earlier release rendered them, and that release's unit installed.
        plan = build_plan(project=SLUG, owner_user=TENANT, owner_home=home, source_repo=release, service_user="boardsvc")
        rendered = launcher.render_privileged_artifacts(plan)
        current_unit = rendered[plan.board_unit].decode("utf-8")
        old_unit = earlier_release_unit(current_unit)
        installed = launcher.install_privileged_artifacts(plan, {**rendered, plan.board_unit: old_unit.encode("utf-8")})
        system_units = root / "systemd"
        system_units.mkdir()
        (system_units / plan.board_unit).write_text(old_unit, encoding="utf-8")
        check(os.stat(installed / "plan.json").st_uid == 0 and (installed / plan.board_unit).read_text() == old_unit,
              "the fixture: a root-owned record, and the earlier release's unit in it and installed")
        tenant_before = {path: (path.read_bytes(), path.stat().st_ino, stat.S_IMODE(path.stat().st_mode))
                         for path in (readme, board_env)}
        unfinished = launcher.PacketCompletion((f"the board does not answer on port {plan.port}",))

        def resume():
            said: list[str] = []
            with owner_patches(home):
                status = launcher.switchyard_resume_provision_command(
                    SLUG, registry_dir=registry, euid_getter=lambda: 0, source_repo=release,
                    completion_reader=lambda _plan: unfinished, print_func=said.append)
            return status, said

        status, said = resume()
        check(status == 1 and any("operator-commands.sh" in line and "re-runnable" in line for line in said)
              and any(f"resume-provision {SLUG}" in line and "again" in line for line in said),
              f"resuming hands back the packet to finish, and says to resume again after it: {said}")
        regenerated = (installed / plan.board_unit).read_text(encoding="utf-8")
        check(regenerated == current_unit and "Wants=postgresql.service" not in regenerated and "RestartSec=30s" in regenerated,
              "root's unit is regenerated by the current release, not the one the earlier release rendered")
        packet = (installed / "operator-commands.sh").read_text(encoding="utf-8")
        check(f"{SLUG}-database.sql" in packet and f"/etc/systemd/system/{plan.board_unit}" in packet
              and f"test -s '{board_env}'" in packet.split(f"{SLUG}-database.sql")[0],
              "the packet handed back creates the database and installs that unit, and keeps an existing board env file")
        check({path: (path.read_bytes(), path.stat().st_ino, stat.S_IMODE(path.stat().st_mode)) for path in tenant_before}
              == tenant_before, "the account's repository and credentials are untouched, by bytes, inode and mode")
        check((system_units / plan.board_unit).read_text() == old_unit and not (registry / f"{SLUG}.json").exists(),
              "resuming installs nothing and registers nothing before the packet has run")
        snapshot = {p.name: p.read_bytes() for p in installed.iterdir() if p.is_file()}
        status, _said = resume()
        check(status == 1 and {p.name: p.read_bytes() for p in installed.iterdir() if p.is_file()} == snapshot,
              "and resuming again changes nothing more")


def main() -> int:
    if "--privileged-child" in sys.argv:
        privileged_cases()
        print(f"stranded_provision_retry_test: privileged child ran {CHECKS} checks")
        return 0
    for name, value in sorted(globals().items()):
        if name.startswith("test_") and callable(value):
            value()
    unprivileged = CHECKS
    if not namespaces_available():
        print("stranded_provision_retry_test: user namespaces are unavailable, so the resume half cannot run")
        return 1
    done = subprocess.run(["unshare", "--user", "--map-root-user", sys.executable, __file__, "--privileged-child"],
                          text=True, capture_output=True)
    if done.returncode != 0:
        print(done.stdout + done.stderr)
        return 1
    print(done.stdout.strip())
    print(f"stranded_provision_retry_test: {unprivileged} unprivileged checks ok")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
