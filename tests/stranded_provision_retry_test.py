#!/usr/bin/env python3
"""SYRD-260: a `switchyard new` stranded between its board unit and its database has a way forward.

On the SYRD-248 VM the operator packet installed the board unit, failed on the
polkit rule that follows it, and never reached the database. SYRD-261 let a
re-run through when the installed unit is byte-for-byte the one the current
release renders. It is not when the release changed in between -- the operator
upgraded to get the very fix the run lacked, and SYRD-552 has since changed the
board unit -- and that re-run was refused with only `switchyard teardown`.

Root's own provisioning record, which `switchyard new` installs before the
packet runs, is what recognises the run as this project's.
`resume-provision` verifies that record and rebuilds root's artifacts from it,
so the precheck now names that command, after any prerequisite it found.

- The precheck half drives the real `new_project_command` against a unit the
  previous release rendered, with root's record present, absent, or a symlink.
- The resume half runs in a user namespace, where this process is uid 0 and owns
  what root owns. It builds the stranded state with the product's own renderer
  and installer, then resumes it: root's unit is regenerated by the current
  release, the re-runnable packet is handed back, and the account's files are
  untouched.

No real unit, database, account or service is touched: the runner is a
recorder, the unit and provisioning directories are temporary, and the owner
lookups are stood in.
"""

